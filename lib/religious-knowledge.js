'use strict';

function normalizeReligiousQuestion(value) {
  return String(value || '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u0640]/gu, '')
    .replace(/[يى]/gu, 'ی')
    .replace(/ك/gu, 'ک')
    .replace(/[ۀة]/gu, 'ه')
    .replace(/[أإآ]/gu, 'ا')
    .replace(/\s+/gu, ' ')
    .trim();
}

function isMinorSignsQuestion(question) {
  const value = normalizeReligiousQuestion(question);
  if (!value) return false;

  const mentionsHour =
    /(?:قیامت|الساعة|الساعه|اشراط\s*الساعه|اشراط\s*الساعة|اخرت|اخرت ورځ|day of judgment|day of judgement|hour signs)/u.test(value);
  if (!mentionsHour) return false;

  // Do not answer a clearly major-signs question with a minor-signs article.
  const asksMajorSigns =
    /(?:لوی[ېی]?\s*(?:نښې|نښانې)|کبرى\s*(?:نښې|علامات)|نښې\s*کبری|major\s+signs|major signs of the hour|اشراط\s*الساعة\s*الكبرى)/u.test(value);
  if (asksMajorSigns) return false;

  const explicitMinorSigns =
    /(?:وړ[ېيه]?\s*(?:نښې|نښانې)|کوچن[ۍيی]?\s*(?:نښې|نښانې)|صغرى|صغری|minor\s+signs|minor signs of the hour)/u.test(value);
  const generalSigns =
    /(?:قیامت.{0,28}(?:نښې|نښانې)|(?:نښې|نښانې).{0,28}قیامت|اشراط\s*الساعه|اشراط\s*الساعة|signs of the hour|signs of the day of judgment)/u.test(value);

  return explicitMinorSigns || generalSigns;
}

